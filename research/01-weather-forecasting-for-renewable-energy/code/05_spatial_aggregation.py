"""Step 5: how forecast errors average out across sites (Proposition 2).

Uses the day-ahead (24-48 h) 10 m wind speed errors of the bias-corrected
multi-model mean for the evaluation runs (June-July 2025). Bias correction
removes the systematic day-night error, which would otherwise appear as a
spurious correlation between stations.

  * Error correlation between every pair of stations versus their distance.
  * RMSE of the error of an N-station average, relative to the mean
    single-station RMSE, for random subsets of N stations, compared with the
    equal-variance formula sqrt((1 + (N - 1) r) / N), r = mean pairwise correlation.

Inputs  : data/interim/verification_wide.csv.gz, data/processed/stations.csv
Outputs : data/processed/fig06a_error_correlation_pairs.csv  (one row per pair)
          data/processed/fig06a_error_correlation_binned.csv
          data/processed/fig06b_aggregation_rmse_vs_n.csv
          paper/generated/values-05-aggregation.tex
"""

from __future__ import annotations

import itertools

import numpy as np
import pandas as pd

import config as C
from common import haversine_km, write_tex


def main() -> None:
    w = pd.read_csv(C.INTERIM_DIR / "verification_wide.csv.gz", parse_dates=["init_time_utc"])
    w = w[w.step_h.isin(C.DAY_AHEAD_STEPS_H) & (w.init_time_utc >= pd.Timestamp(C.EVAL_FIRST_INIT, tz="UTC"))]
    w["err"] = w.wind_fc_mmm_bc - w.wind_obs
    E = w.pivot_table(index=["init_time_utc", "step_h"], columns="station_id", values="err")
    E = E.dropna(axis=0, thresh=int(0.8 * E.shape[1]))  # keep times where most stations report

    st = pd.read_csv(C.PROCESSED_DIR / "stations.csv").set_index("station_id")
    corr = E.corr(min_periods=60)
    rows = []
    for a, b in itertools.combinations(E.columns, 2):
        d = haversine_km(st.at[a, "latitude"], st.at[a, "longitude"], st.at[b, "latitude"], st.at[b, "longitude"])
        rows.append({"station_a": a, "station_b": b, "distance_km": round(d, 1),
                     "error_correlation": round(corr.at[a, b], 4)})
    pairs = pd.DataFrame(rows)
    pairs.to_csv(C.PROCESSED_DIR / "fig06a_error_correlation_pairs.csv", index=False)

    bins = np.arange(0, 901, 100)
    pairs["bin"] = pd.cut(pairs.distance_km, bins)
    binned = pairs.groupby("bin", observed=True).error_correlation.agg(["mean", "count",
                                                                        lambda s: s.quantile(0.25),
                                                                        lambda s: s.quantile(0.75)])
    binned.columns = ["mean_correlation", "pairs", "q25", "q75"]
    binned["distance_mid_km"] = [iv.mid for iv in binned.index]
    binned.reset_index(drop=True).round(4).to_csv(C.PROCESSED_DIR / "fig06a_error_correlation_binned.csv", index=False)

    # aggregation experiment
    rng = np.random.default_rng(C.RANDOM_SEED)
    cols = list(E.columns)
    single_rmse = np.sqrt((E ** 2).mean()).mean()
    rbar = pairs.error_correlation.mean()
    out = []
    for n in range(1, len(cols) + 1):
        reps = 1 if n == len(cols) else 300
        vals = []
        for _ in range(reps):
            sub = rng.choice(cols, size=n, replace=False)
            avg_err = E[sub].mean(axis=1, skipna=True)
            vals.append(np.sqrt((avg_err ** 2).mean()))
        out.append({"n_stations": n, "relative_rmse": np.mean(vals) / single_rmse,
                    "relative_rmse_q10": np.quantile(vals, 0.1) / single_rmse,
                    "relative_rmse_q90": np.quantile(vals, 0.9) / single_rmse,
                    "theory": np.sqrt((1 + (n - 1) * rbar) / n)})
    agg = pd.DataFrame(out)
    agg.round(4).to_csv(C.PROCESSED_DIR / "fig06b_aggregation_rmse_vs_n.csv", index=False)

    near = pairs[pairs.distance_km < 100].error_correlation.mean()
    far = pairs[pairs.distance_km > 500].error_correlation.mean()
    full = agg.iloc[-1].relative_rmse
    lines = ["% Generated by code/05_spatial_aggregation.py -- do not edit by hand.",
             f"\\newcommand{{\\valAggMeanCorr}}{{{rbar:.2f}}}",
             f"\\newcommand{{\\valAggCorrNear}}{{{near:.2f}}}",
             f"\\newcommand{{\\valAggCorrFar}}{{{far:.2f}}}",
             f"\\newcommand{{\\valAggRelRmseAll}}{{{full:.2f}}}",
             f"\\newcommand{{\\valAggRelRmseAllPct}}{{{100 * (1 - full):.0f}}}",
             f"\\newcommand{{\\valAggTheoryLimit}}{{{np.sqrt(rbar):.2f}}}",
             f"\\newcommand{{\\valAggNumPairs}}{{{len(pairs):,}}}",
             f"\\newcommand{{\\valAggSingleRmse}}{{{single_rmse:.2f}}}"]
    write_tex(C.GENERATED_TEX_DIR / "values-05-aggregation.tex", lines)
    print(binned)
    print(agg.iloc[[0, 4, 9, 19, -1]])


if __name__ == "__main__":
    main()
