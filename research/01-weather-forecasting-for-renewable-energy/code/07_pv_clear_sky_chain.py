"""Step 7: the PV modelling chain on a clear-sky day (illustration).

A 10 MWp / 7.7 MWac fixed-tilt plant near Leipzig on 21 June 2025.

  irradiance   Ineichen-Perez clear-sky GHI, DNI, DHI with the monthly Linke
               turbidity climatology shipped with pvlib (a model, not a measurement)
  weather      observed air temperature and 10 m wind speed at Leipzig-Halle
               airport (NOAA ISD), interpolated to 10-minute steps
  chain        NREL SPA solar position -> Perez transposition -> ASHRAE IAM on the
               beam component -> Faiman cell temperature -> PVWatts DC power ->
               constant-efficiency inverter with AC clipping

Inputs  : data/interim/station_observations_2025.csv.gz
Outputs : data/processed/fig03_pv_chain_clear_day.csv
          paper/generated/values-07-pv.tex
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pvlib

import config as C
from common import write_tex


def main() -> None:
    site, plant = C.PV_SITE, C.PV_PLANT
    loc = pvlib.location.Location(site["latitude"], site["longitude"], tz="UTC", altitude=site["altitude"])
    day = pd.Timestamp(C.PV_DAY, tz="UTC")
    times = pd.date_range(day, day + pd.Timedelta("1D"), freq="10min", inclusive="left")

    # observed weather at the site
    obs = pd.read_csv(C.INTERIM_DIR / "station_observations_2025.csv.gz", parse_dates=["time_utc"])
    obs = obs[(obs.station_id == site["station_id"])
              & (obs.time_utc >= day - pd.Timedelta("2h")) & (obs.time_utc <= day + pd.Timedelta("26h"))]
    obs = obs.groupby("time_utc")[["temperature_2m_c", "wind_speed_10m_ms"]].mean()
    met = obs.reindex(obs.index.union(times)).interpolate(method="time").reindex(times)

    # irradiance and geometry
    sp = loc.get_solarposition(times)
    cs = loc.get_clearsky(times, model="ineichen", solar_position=sp)
    dni_extra = pvlib.irradiance.get_extra_radiation(times)
    airmass = pvlib.atmosphere.get_relative_airmass(sp.apparent_zenith, model="kastenyoung1989")
    poa = pvlib.irradiance.get_total_irradiance(
        plant["tilt_deg"], plant["azimuth_deg"], sp.apparent_zenith, sp.azimuth,
        cs.dni, cs.ghi, cs.dhi, dni_extra=dni_extra, airmass=airmass,
        albedo=plant["albedo"], model="perez")
    aoi = pvlib.irradiance.aoi(plant["tilt_deg"], plant["azimuth_deg"], sp.apparent_zenith, sp.azimuth)
    iam = pvlib.iam.ashrae(aoi, b=0.05)
    poa_eff = (poa.poa_direct * iam + poa.poa_diffuse).clip(lower=0).fillna(0)

    t_cell = pvlib.temperature.faiman(poa.poa_global.fillna(0), met.temperature_2m_c, met.wind_speed_10m_ms)
    p_dc = pvlib.pvsystem.pvwatts_dc(poa_eff, t_cell, plant["p_dc_kw"], plant["gamma_pdc"])
    p_dc_25 = pvlib.pvsystem.pvwatts_dc(poa_eff, 25.0, plant["p_dc_kw"], plant["gamma_pdc"])
    p_ac_unclipped = plant["inverter_eta"] * p_dc
    p_ac = np.minimum(p_ac_unclipped, plant["p_ac_kw"])

    out = pd.DataFrame({
        "time_utc": times.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "hour_utc": times.hour + times.minute / 60,
        "solar_zenith_deg": sp.apparent_zenith.to_numpy(),
        "ghi_wm2": cs.ghi.to_numpy(), "dni_wm2": cs.dni.to_numpy(), "dhi_wm2": cs.dhi.to_numpy(),
        "poa_global_wm2": poa.poa_global.fillna(0).to_numpy(),
        "air_temperature_c": met.temperature_2m_c.to_numpy(),
        "wind_speed_ms": met.wind_speed_10m_ms.to_numpy(),
        "cell_temperature_c": t_cell.to_numpy(),
        "p_dc_mw": (p_dc / 1000).to_numpy(), "p_dc_at_25c_mw": (p_dc_25 / 1000).to_numpy(),
        "p_ac_unclipped_mw": (p_ac_unclipped / 1000).to_numpy(), "p_ac_mw": (p_ac / 1000).to_numpy(),
    })
    out.round(4).to_csv(C.PROCESSED_DIR / "fig03_pv_chain_clear_day.csv", index=False)

    h = 1 / 6  # 10-minute steps in hours
    e_dc25 = p_dc_25.sum() * h / 1000
    e_dc = p_dc.sum() * h / 1000
    e_ac_unc = p_ac_unclipped.sum() * h / 1000
    e_ac = p_ac.sum() * h / 1000
    h_ghi = cs.ghi.sum() * h / 1000
    h_poa = poa.poa_global.fillna(0).sum() * h / 1000
    noon = sp.apparent_zenith.idxmin()
    lines = ["% Generated by code/07_pv_clear_sky_chain.py -- do not edit by hand.",
             f"\\newcommand{{\\valPvGhiKwh}}{{{h_ghi:.2f}}}",
             f"\\newcommand{{\\valPvPoaKwh}}{{{h_poa:.2f}}}",
             f"\\newcommand{{\\valPvEnergyAcMwh}}{{{e_ac:.1f}}}",
             f"\\newcommand{{\\valPvTempLossPct}}{{{100 * (1 - e_dc / e_dc25):.1f}}}",
             f"\\newcommand{{\\valPvClipLossPct}}{{{100 * (1 - e_ac / e_ac_unc):.1f}}}",
             f"\\newcommand{{\\valPvClipHours}}{{{(p_ac_unclipped > plant['p_ac_kw']).sum() * h:.1f}}}",
             f"\\newcommand{{\\valPvMaxCellTemp}}{{{t_cell.max():.0f}}}",
             f"\\newcommand{{\\valPvMaxAirTemp}}{{{met.temperature_2m_c.max():.0f}}}",
             f"\\newcommand{{\\valPvSolarNoonUtc}}{{{noon:%H:%M}}}",
             f"\\newcommand{{\\valPvMinZenith}}{{{sp.apparent_zenith.min():.1f}}}"]
    write_tex(C.GENERATED_TEX_DIR / "values-07-pv.tex", lines)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
